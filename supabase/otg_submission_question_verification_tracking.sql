-- OTG GRAPHIC Academy: per-student, per-question verification tracking.
-- Additive only; preserves all existing assignment/submission data. Safe to rerun.

create table if not exists public.academy_submission_question_verifications (
  id bigint generated by default as identity primary key,
  submission_id bigint not null references public.academy_submissions(id) on delete cascade,
  assignment_id bigint not null references public.academy_assignments(id) on delete cascade,
  student_id uuid not null references auth.users(id) on delete cascade,
  question_number integer not null check (question_number > 0),
  status text not null default 'pending'
    check (status in ('pending','verified','needs_followup')),
  evidence_reviewed boolean not null default false,
  reviewer_notes text not null default '',
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (submission_id, question_number)
);

create index if not exists academy_submission_question_verifications_submission_idx
  on public.academy_submission_question_verifications (submission_id, question_number);
create index if not exists academy_submission_question_verifications_student_idx
  on public.academy_submission_question_verifications (student_id, status);

alter table public.academy_submission_question_verifications enable row level security;

do $otg$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname='public' and tablename='academy_submission_question_verifications'
      and policyname='Admins manage question verification records'
  ) then
    create policy "Admins manage question verification records"
      on public.academy_submission_question_verifications for all to authenticated
      using ((select public.is_otg_admin()))
      with check ((select public.is_otg_admin()));
  end if;
  if not exists (
    select 1 from pg_policies
    where schemaname='public' and tablename='academy_submission_question_verifications'
      and policyname='Students read their own question verification records'
  ) then
    create policy "Students read their own question verification records"
      on public.academy_submission_question_verifications for select to authenticated
      using (student_id = (select auth.uid()) and (select public.is_otg_approved_student()));
  end if;
end;
$otg$;

grant select, insert, update, delete on public.academy_submission_question_verifications to authenticated;
grant usage, select on sequence public.academy_submission_question_verifications_id_seq to authenticated;

select table_name from information_schema.tables
where table_schema='public' and table_name='academy_submission_question_verifications';
