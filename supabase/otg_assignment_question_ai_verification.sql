-- OTG GRAPHIC Academy: question-by-question AI verification controls.
-- Additive migration only. Does not drop, replace, or rewrite existing academy data.
-- Run once in Supabase SQL Editor. Safe to rerun.

create table if not exists public.academy_assignment_question_policies (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.academy_assignments(id) on delete cascade,
  question_number integer not null check (question_number > 0),
  ai_use_policy text not null default 'allow'
    check (ai_use_policy in ('allow','restrict','prohibit')),
  verification_enabled boolean not null default false,
  verification_method text not null default 'lecturer_review'
    check (verification_method in ('practical_task','oral_explanation','lecturer_review')),
  require_explanation boolean not null default false,
  required_evidence text[] not null default '{}',
  lecturer_notes text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (assignment_id, question_number)
);

create index if not exists academy_assignment_question_policies_assignment_idx
  on public.academy_assignment_question_policies (assignment_id, question_number);

alter table public.academy_assignment_question_policies enable row level security;

do $otg$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname='public' and tablename='academy_assignment_question_policies'
      and policyname='Admins manage question AI verification policies'
  ) then
    create policy "Admins manage question AI verification policies"
      on public.academy_assignment_question_policies for all to authenticated
      using ((select public.is_otg_admin()))
      with check ((select public.is_otg_admin()));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname='public' and tablename='academy_assignment_question_policies'
      and policyname='Approved students read policies for published assignments'
  ) then
    create policy "Approved students read policies for published assignments"
      on public.academy_assignment_question_policies for select to authenticated
      using (
        (select public.is_otg_approved_student())
        and exists (
          select 1 from public.academy_assignments a
          where a.id = assignment_id and a.is_published = true
            and (a.assigned_to is null or a.assigned_to = (select auth.uid()))
        )
      );
  end if;
end;
$otg$;

grant select on public.academy_assignment_question_policies to authenticated;
grant insert, update, delete on public.academy_assignment_question_policies to authenticated;
grant usage, select on sequence public.academy_assignment_question_policies_id_seq to authenticated;

