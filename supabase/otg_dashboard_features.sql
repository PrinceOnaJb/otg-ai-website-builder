-- OTG GRAPHIC Academy: dashboard feature tables and row-level security
-- Run after supabase/otg_academy_coordinated_setup.sql.
-- This file is additive: it does not drop existing student, project, product, or lesson data.

CREATE OR REPLACE FUNCTION public.set_otg_profile_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$function$;

-- Certificates
CREATE TABLE IF NOT EXISTS public.academy_certificates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  course text NOT NULL CHECK (length(trim(course)) > 0),
  certificate_code text NOT NULL UNIQUE DEFAULT ('OTG-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))),
  issued_at timestamptz NOT NULL DEFAULT now(),
  issued_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'issued' CHECK (status IN ('issued','revoked')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_academy_certificates_student_id ON public.academy_certificates(student_id);
CREATE INDEX IF NOT EXISTS idx_academy_certificates_status ON public.academy_certificates(status);
CREATE INDEX IF NOT EXISTS idx_academy_certificates_issued_by ON public.academy_certificates(issued_by);
ALTER TABLE public.academy_certificates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.academy_certificates FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.academy_certificates TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.academy_certificates_id_seq TO authenticated;
DROP POLICY IF EXISTS "OTG admins manage certificates" ON public.academy_certificates;
CREATE POLICY "OTG admins manage certificates" ON public.academy_certificates
  FOR ALL TO authenticated USING ((SELECT public.is_otg_admin()))
  WITH CHECK ((SELECT public.is_otg_admin()));
DROP POLICY IF EXISTS "Approved students read own issued certificates" ON public.academy_certificates;
CREATE POLICY "Approved students read own issued certificates" ON public.academy_certificates
  FOR SELECT TO authenticated USING (
    student_id = (SELECT auth.uid()) AND status = 'issued'
    AND (SELECT public.is_otg_approved_student())
  );

-- Opt-in student directory profiles. Email addresses are deliberately not stored in this table.
CREATE TABLE IF NOT EXISTS public.academy_student_profiles (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name text NOT NULL DEFAULT '' CHECK (length(display_name) <= 100),
  country text NOT NULL DEFAULT '' CHECK (length(country) <= 100),
  bio text NOT NULL DEFAULT '' CHECK (length(bio) <= 800),
  interests text NOT NULL DEFAULT '' CHECK (length(interests) <= 300),
  is_discoverable boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_academy_student_profiles_discoverable ON public.academy_student_profiles(is_discoverable) WHERE is_discoverable = true;
ALTER TABLE public.academy_student_profiles ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.academy_student_profiles FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE ON TABLE public.academy_student_profiles TO authenticated;
DROP POLICY IF EXISTS "Approved students view opted-in profiles" ON public.academy_student_profiles;
CREATE POLICY "Approved students view opted-in profiles" ON public.academy_student_profiles
  FOR SELECT TO authenticated USING (
    (user_id = (SELECT auth.uid()) OR is_discoverable = true)
    AND (SELECT public.is_otg_approved_student())
  );
DROP POLICY IF EXISTS "Students create own academy profile" ON public.academy_student_profiles;
CREATE POLICY "Students create own academy profile" ON public.academy_student_profiles
  FOR INSERT TO authenticated WITH CHECK (
    user_id = (SELECT auth.uid()) AND (SELECT public.is_otg_approved_student())
  );
DROP POLICY IF EXISTS "Students update own academy profile" ON public.academy_student_profiles;
CREATE POLICY "Students update own academy profile" ON public.academy_student_profiles
  FOR UPDATE TO authenticated
  USING (user_id = (SELECT auth.uid()) AND (SELECT public.is_otg_approved_student()))
  WITH CHECK (user_id = (SELECT auth.uid()) AND (SELECT public.is_otg_approved_student()));
DROP POLICY IF EXISTS "OTG admins manage academy student profiles" ON public.academy_student_profiles;
CREATE POLICY "OTG admins manage academy student profiles" ON public.academy_student_profiles
  FOR ALL TO authenticated USING ((SELECT public.is_otg_admin()))
  WITH CHECK ((SELECT public.is_otg_admin()));
DROP TRIGGER IF EXISTS set_academy_student_profile_updated_at ON public.academy_student_profiles;
CREATE TRIGGER set_academy_student_profile_updated_at BEFORE UPDATE ON public.academy_student_profiles
  FOR EACH ROW EXECUTE FUNCTION public.set_otg_profile_updated_at();

-- Connection requests: students can initiate requests to discoverable profiles; only the recipient can respond.
CREATE TABLE IF NOT EXISTS public.academy_connection_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  target_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  message text NOT NULL DEFAULT '' CHECK (length(message) <= 500),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','declined')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT academy_connection_not_self CHECK (requester_id <> target_id),
  CONSTRAINT academy_connection_unique_pair UNIQUE (requester_id,target_id)
);
CREATE INDEX IF NOT EXISTS idx_academy_connection_requests_target_status ON public.academy_connection_requests(target_id,status);
CREATE INDEX IF NOT EXISTS idx_academy_connection_requests_requester_status ON public.academy_connection_requests(requester_id,status);
ALTER TABLE public.academy_connection_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.academy_connection_requests FROM PUBLIC, anon;
GRANT SELECT, INSERT ON TABLE public.academy_connection_requests TO authenticated;
GRANT UPDATE(status,updated_at) ON TABLE public.academy_connection_requests TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.academy_connection_requests_id_seq TO authenticated;
DROP POLICY IF EXISTS "Students view own connection requests" ON public.academy_connection_requests;
CREATE POLICY "Students view own connection requests" ON public.academy_connection_requests
  FOR SELECT TO authenticated USING (
    (requester_id = (SELECT auth.uid()) OR target_id = (SELECT auth.uid()))
    AND (SELECT public.is_otg_approved_student())
  );
DROP POLICY IF EXISTS "Approved students request discoverable connections" ON public.academy_connection_requests;
CREATE POLICY "Approved students request discoverable connections" ON public.academy_connection_requests
  FOR INSERT TO authenticated WITH CHECK (
    requester_id = (SELECT auth.uid()) AND status = 'pending'
    AND (SELECT public.is_otg_approved_student())
    AND EXISTS (
      SELECT 1 FROM public.academy_student_profiles sp
      WHERE sp.user_id = target_id AND sp.is_discoverable = true
    )
  );
DROP POLICY IF EXISTS "Targets respond to connection requests" ON public.academy_connection_requests;
CREATE POLICY "Targets respond to connection requests" ON public.academy_connection_requests
  FOR UPDATE TO authenticated
  USING (target_id = (SELECT auth.uid()) AND status = 'pending' AND (SELECT public.is_otg_approved_student()))
  WITH CHECK (target_id = (SELECT auth.uid()) AND status IN ('accepted','declined') AND (SELECT public.is_otg_approved_student()));
DROP POLICY IF EXISTS "OTG admins manage connection requests" ON public.academy_connection_requests;
CREATE POLICY "OTG admins manage connection requests" ON public.academy_connection_requests
  FOR ALL TO authenticated USING ((SELECT public.is_otg_admin()))
  WITH CHECK ((SELECT public.is_otg_admin()));
DROP TRIGGER IF EXISTS set_academy_connection_request_updated_at ON public.academy_connection_requests;
CREATE TRIGGER set_academy_connection_request_updated_at BEFORE UPDATE ON public.academy_connection_requests
  FOR EACH ROW EXECUTE FUNCTION public.set_otg_profile_updated_at();

-- Website review requests and coach feedback.
CREATE TABLE IF NOT EXISTS public.academy_website_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  student_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  request_message text NOT NULL DEFAULT '' CHECK (length(request_message) <= 1500),
  status text NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','in_review','completed')),
  rating smallint CHECK (rating BETWEEN 1 AND 5),
  feedback text NOT NULL DEFAULT '' CHECK (length(feedback) <= 4000),
  reviewer_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  project_title text NOT NULL DEFAULT 'Website project',
  project_slug text,
  project_is_published boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_academy_website_reviews_student_id ON public.academy_website_reviews(student_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_academy_website_reviews_project_id ON public.academy_website_reviews(project_id);
CREATE INDEX IF NOT EXISTS idx_academy_website_reviews_status ON public.academy_website_reviews(status);
CREATE INDEX IF NOT EXISTS idx_academy_website_reviews_reviewer_id ON public.academy_website_reviews(reviewer_id);
ALTER TABLE public.academy_website_reviews ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.academy_website_reviews FROM PUBLIC, anon;
GRANT SELECT, INSERT ON TABLE public.academy_website_reviews TO authenticated;
GRANT UPDATE(status,rating,feedback,reviewer_id,reviewed_at,updated_at) ON TABLE public.academy_website_reviews TO authenticated;
DROP POLICY IF EXISTS "Students read own website reviews" ON public.academy_website_reviews;
CREATE POLICY "Students read own website reviews" ON public.academy_website_reviews
  FOR SELECT TO authenticated USING (
    student_id = (SELECT auth.uid()) AND (SELECT public.is_otg_approved_student())
  );
DROP POLICY IF EXISTS "Students request reviews for own projects" ON public.academy_website_reviews;
CREATE POLICY "Students request reviews for own projects" ON public.academy_website_reviews
  FOR INSERT TO authenticated WITH CHECK (
    student_id = (SELECT auth.uid()) AND (SELECT public.is_otg_approved_student())
    AND EXISTS (
      SELECT 1 FROM public.projects p
      WHERE p.id = project_id AND p.user_id = (SELECT auth.uid())
    )
  );
DROP POLICY IF EXISTS "OTG admins manage website reviews" ON public.academy_website_reviews;
CREATE POLICY "OTG admins manage website reviews" ON public.academy_website_reviews
  FOR ALL TO authenticated USING ((SELECT public.is_otg_admin()))
  WITH CHECK ((SELECT public.is_otg_admin()));
DROP TRIGGER IF EXISTS set_academy_website_review_updated_at ON public.academy_website_reviews;
CREATE TRIGGER set_academy_website_review_updated_at BEFORE UPDATE ON public.academy_website_reviews
  FOR EACH ROW EXECUTE FUNCTION public.set_otg_profile_updated_at();

-- Privacy-limited public website view counts.
CREATE TABLE IF NOT EXISTS public.academy_website_page_views (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  viewed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_academy_website_page_views_project_viewed
  ON public.academy_website_page_views(project_id,viewed_at DESC);
ALTER TABLE public.academy_website_page_views ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.academy_website_page_views FROM PUBLIC;
GRANT INSERT ON TABLE public.academy_website_page_views TO anon, authenticated;
GRANT SELECT ON TABLE public.academy_website_page_views TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.academy_website_page_views_id_seq TO anon, authenticated;
DROP POLICY IF EXISTS "Count views of published OTG websites" ON public.academy_website_page_views;
CREATE POLICY "Count views of published OTG websites" ON public.academy_website_page_views
  FOR INSERT TO anon, authenticated WITH CHECK (
    EXISTS (SELECT 1 FROM public.projects p WHERE p.id = project_id AND p.is_published = true)
  );
DROP POLICY IF EXISTS "Owners read views for own projects" ON public.academy_website_page_views;
CREATE POLICY "Owners read views for own projects" ON public.academy_website_page_views
  FOR SELECT TO authenticated USING (
    EXISTS (SELECT 1 FROM public.projects p WHERE p.id = project_id AND p.user_id = (SELECT auth.uid()))
  );

-- Keep approval helpers callable by signed-in users for RLS policy checks, not by anonymous callers.
REVOKE ALL ON FUNCTION public.is_otg_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_otg_admin() TO authenticated;
REVOKE ALL ON FUNCTION public.is_otg_approved() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_otg_approved() TO authenticated;
REVOKE ALL ON FUNCTION public.is_otg_approved_student() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_otg_approved_student() TO authenticated;
